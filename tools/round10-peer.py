#!/usr/bin/env python3
"""round10-peer.py -- the peer for round 10's controlled batch.

WHY UDP RATHER THAN TCP
-----------------------
Round 9 used TCP and then had to admit it could not say "this 42-byte DMA is
that ACK": one write() is not one segment, an ACK is generated by the peer's
stack rather than by the application, and TCP reordering/retransmission makes
the mapping non-unique. The report's link between a driver record and a client
sequence number was time order plus a length, which is not an identifier.

A small UDP echo removes all of that. One sendto() is one datagram, one
datagram is one (or a known small number of) descriptor, and the peer echoes
the SAME identifier bytes back. The identifier is what the driver parses out
of the payload, so the join is by value, not by timing.

WIRE FORMAT (12 bytes at the start of every payload)
----------------------------------------------------
    offset 0..3   magic  'IOB1' = 0x31424F49  (big endian)
    offset 4..7   runToken  (big endian)
    offset 8..11  reqId     (big endian)
    offset 12..   padding, echoed unchanged

The driver reads exactly these 12 bytes (see obsParseBiz in RTL812xLucy.cpp).
The magic exists so the driver can tell "a datagram from this experiment" from
"some other UDP traffic on the same interface" -- without it, a stray DNS query
could be mistaken for a request.

WHAT THIS PEER RECORDS
----------------------
For every datagram: the run token, the request id, the source address/port,
the payload length, and whether the echo was actually sent. That is an
independent record of "the peer saw request N and replied to it".

It never invents a request id: it echoes whatever arrived, so if the client
sent something malformed the peer's log shows it rather than hiding it.
"""
import argparse
import hashlib
import json
import os
import socket
import struct
import sys
import time

MAGIC = 0x31424F49   # 'IOB1'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bind', default='0.0.0.0')
    ap.add_argument('--port', type=int, default=9110)
    ap.add_argument('--out', required=True)
    ap.add_argument('--idle-timeout', type=float, default=180.0)
    ap.add_argument('--expect', type=int, default=0,
                    help='expected request count; used only for a summary')
    a = ap.parse_args()

    out = open(a.out, 'w', encoding='utf-8', newline='\n')
    def log(s):
        out.write(s + '\n')
        out.flush()

    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    s.bind((a.bind, a.port))
    s.settimeout(1.0)

    log('peer_start_ns %d' % time.monotonic_ns())
    log('peer_bind %s:%d' % (a.bind, a.port))
    log('peer_idle_timeout_s %.1f' % a.idle_timeout)
    log('peer_magic 0x%08x' % MAGIC)

    got = 0
    bad = 0
    seen = set()
    last = time.monotonic()
    t_first = 0
    t_last = 0

    while True:
        now = time.monotonic()
        if now - last > a.idle_timeout:
            log('peer_idle_timeout_after %d' % got)
            break
        try:
            data, addr = s.recvfrom(4096)
        except socket.timeout:
            continue
        except KeyboardInterrupt:
            break

        t = time.monotonic_ns()
        if len(data) < 12:
            bad += 1
            log('peer_short len=%d from=%s:%d' % (len(data), addr[0], addr[1]))
            continue
        magic, tok, req = struct.unpack('>III', data[:12])
        if magic != MAGIC:
            bad += 1
            log('peer_bad_magic 0x%08x len=%d from=%s:%d'
                % (magic, len(data), addr[0], addr[1]))
            # Echo anyway so the client is not left hanging, but the log says
            # the datagram was not one of ours.
            s.sendto(data, addr)
            continue

        got += 1
        if t_first == 0:
            t_first = t
        t_last = t
        seen.add(req)
        log('peer_recv token=0x%08x req=%d len=%d from=%s:%d t_ns=%d'
            % (tok, req, len(data), addr[0], addr[1], t))

        # Echo the payload VERBATIM. The driver parses the same 12 bytes out
        # of the reply, so the RX record carries the same (token, reqId) the
        # TX record did. That is the whole join.
        try:
            s.sendto(data, addr)
            log('peer_echo token=0x%08x req=%d ok' % (tok, req))
        except OSError as e:
            bad += 1
            log('peer_echo token=0x%08x req=%d FAIL %s' % (tok, req, e))

        last = time.monotonic()

    span = (t_last - t_first) if t_first and t_last else 0
    contiguous = (got > 0 and seen == set(range(1, max(seen) + 1)))
    log('peer_summary got=%d bad=%d distinct=%d span_ns=%d contiguous=%s'
        % (got, bad, len(seen), span, 'yes' if contiguous else 'no'))
    if a.expect:
        log('peer_expect declared=%d match=%s'
            % (a.expect, 'yes' if got == a.expect else 'no'))
    log('peer_result %s' % ('OK' if bad == 0 and got > 0 else 'PROBLEM'))
    log('peer_end_ns %d' % time.monotonic_ns())
    out.close()
    s.close()
    return 0 if bad == 0 and got > 0 else 1


if __name__ == '__main__':
    sys.exit(main())
