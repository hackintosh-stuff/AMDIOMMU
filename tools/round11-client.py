#!/usr/bin/env python3
"""round11-client.py -- the controlled UDP batch client, run ON THE MAC.

WHY UDP RATHER THAN TCP
-----------------------
Round 9 used TCP and then had to admit it could not say "this 42-byte DMA is
that ACK": one write() is not one segment, an ACK is generated by the peer's
stack rather than by the application, and TCP reordering/retransmission makes
the mapping non-unique.

A small UDP echo removes all of that. One sendto() is one datagram, one
datagram is one (or a known small number of) descriptor, and the peer echoes
the SAME identifier bytes back. The identifier is what the driver parses out of
the payload, so the join is by value, not by timing.

WIRE FORMAT (12 bytes at the start of every payload)
----------------------------------------------------
    offset 0..3   magic  'IOB1' = 0x31424F49  (big endian)
    offset 4..7   runToken  (big endian)
    offset 8..11  reqId     (big endian)
    offset 12..   padding, echoed unchanged

The driver reads exactly these 12 bytes (obsParseBiz in RTL812xLucy.cpp). The
magic exists so the driver can tell "a datagram from this experiment" from
"some other UDP traffic on the same interface" -- without it, a stray DNS query
could be mistaken for a request.

WHAT THIS CLIENT RECORDS
------------------------
Everything the analyser needs to recompute the batch WITHOUT trusting the
probe: the token, each request id, the payload length, the bound address and
port, the route decision, and the echo. The peer's log is joined on the client's
source port, so a log containing several runs of the session is unambiguous.
"""
import argparse
import socket
import struct
import subprocess
import sys
import time

MAGIC = 0x31424F49          # 'IOB1'
PAD = b'\x00' * 20          # 32-byte payload total


def iface_ipv4(iface):
    out = subprocess.run(['ifconfig', iface], capture_output=True, text=True)
    for line in out.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] == 'inet':
            return parts[1]
    return None


def route_for(peer):
    out = subprocess.run(['route', '-n', 'get', peer],
                         capture_output=True, text=True)
    info = {}
    for line in out.stdout.splitlines():
        if ':' in line:
            k, v = line.split(':', 1)
            info[k.strip()] = v.strip()
    return info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--iface', required=True,
                    help='the BSD interface that must carry the traffic')
    ap.add_argument('--peer', required=True, help='peer IP')
    ap.add_argument('--port', type=int, default=9110)
    ap.add_argument('--run-token', required=True,
                    help='decimal or 0x-prefixed; must match the boot-arg')
    ap.add_argument('--requests', type=int, default=4)
    ap.add_argument('--interval-ms', type=int, default=250)
    ap.add_argument('--timeout-ms', type=int, default=1000)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    token = int(a.run_token, 0)
    if token == 0 or token > 0xFFFFFFFF:
        print('run token must be a non-zero 32-bit value', file=sys.stderr)
        return 2

    out = open(a.out, 'w', encoding='utf-8', newline='\n')

    def log(s):
        out.write(s + '\n')
        out.flush()

    log('client_start_ns %d' % time.monotonic_ns())
    log('client_iface %s' % a.iface)
    log('client_peer %s:%d' % (a.peer, a.port))
    log('client_run_token 0x%08x' % token)
    log('client_requests %d' % a.requests)

    local = iface_ipv4(a.iface)
    if not local:
        log('client_result FAIL-no-ipv4-on-%s' % a.iface)
        out.close()
        return 1
    log('client_local %s' % local)

    # ---- refuse to run if the route does not leave through --iface ----
    #
    # This is the check round 9 did not have. Without it, a source-address bind
    # on en0 looks exactly like a successful "controlled transfer" even though
    # the observed device was en2.
    r = route_for(a.peer)
    log('client_route_interface %s' % r.get('interface', 'unknown'))
    log('client_route_gateway %s' % r.get('gateway', 'none'))
    log('client_route_src %s' % r.get('local address', 'none'))
    if r.get('interface') != a.iface:
        log('client_result FAIL-route-leaves-through-%s-not-%s'
            % (r.get('interface', 'unknown'), a.iface))
        out.close()
        return 1

    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.settimeout(a.timeout_ms / 1000.0)
    try:
        s.bind((local, 0))
    except OSError as e:
        log('client_result FAIL-bind-%s' % e)
        out.close()
        return 1
    bound = s.getsockname()
    log('client_bound %s:%d' % (bound[0], bound[1]))

    sent = 0
    acked = 0
    bad = 0
    t0 = time.monotonic_ns()

    for req in range(1, a.requests + 1):
        payload = struct.pack('>III', MAGIC, token, req) + PAD
        tsend = time.monotonic_ns()
        try:
            s.sendto(payload, (a.peer, a.port))
        except OSError as e:
            bad += 1
            log('client_send_fail req=%d %s' % (req, e))
            continue
        sent += 1
        log('client_sent token=0x%08x req=%d len=%d t_ns=%d'
            % (token, req, len(payload), tsend))

        try:
            data, addr = s.recvfrom(4096)
        except socket.timeout:
            log('client_timeout token=0x%08x req=%d' % (token, req))
            bad += 1
            continue
        trecv = time.monotonic_ns()
        if data != payload:
            bad += 1
            log('client_echo_mismatch token=0x%08x req=%d got=%d want=%d'
                % (token, req, len(data), len(payload)))
            continue
        magic, tok, rq = struct.unpack('>III', data[:12])
        if magic != MAGIC or tok != token or rq != req:
            bad += 1
            log('client_echo_wrong_id token=0x%08x req=%d got_token=0x%08x '
                'got_req=%d' % (token, req, tok, rq))
            continue
        acked += 1
        log('client_recv token=0x%08x req=%d t_ns=%d rtt_ns=%d'
            % (token, req, trecv, trecv - tsend))

        if req < a.requests:
            time.sleep(a.interval_ms / 1000.0)

    t1 = time.monotonic_ns()
    log('client_summary sent=%d acked=%d bad=%d span_ns=%d'
        % (sent, acked, bad, t1 - t0))
    ok = (sent == a.requests and acked == a.requests and bad == 0)
    log('client_result %s' % ('OK' if ok else 'PROBLEM'))
    log('client_end_ns %d' % time.monotonic_ns())
    out.close()
    s.close()
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
